// Auto-generates src/data/timezones.ts from the ICU/IANA timezone database.
// Zero manual city-typing — re-run this any time Node's ICU data updates
// (new zones, renamed zones) and the app picks them up automatically.
//
// Run: node scripts/generate-timezones.mjs
import { writeFileSync } from "node:fs";

const raw = Intl.supportedValuesOf("timeZone"); // ~418 canonical IANA zones, auto-sourced

function slugify(str) {
  return str.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

function cityFromZone(tz) {
  const parts = tz.split("/");
  return parts[parts.length - 1].replace(/_/g, " ");
}

const seenSlugs = new Set();
const entries = [];

// UTC first, always available, not part of the Area/City raw list.
entries.push({ slug: "utc", city: "UTC", region: "UTC", tz: "UTC" });
seenSlugs.add("utc");

for (const tz of raw) {
  if (!tz.includes("/")) continue; // skip bare zones like "UTC" (already added) / oddities
  const region = tz.split("/")[0];
  const city = cityFromZone(tz);
  let slug = slugify(city);
  // De-dupe city-name collisions (e.g. multiple "San Jose") by suffixing the region.
  if (seenSlugs.has(slug)) slug = slugify(`${city}-${region}`);
  if (seenSlugs.has(slug)) continue; // still colliding — extremely rare, skip
  seenSlugs.add(slug);
  entries.push({ slug, city, region, tz });
}

entries.sort((a, b) => a.city.localeCompare(b.city));

// IANA zones represent *regions*, not every major city — e.g. Mumbai, Bangalore
// and Chennai all share "Asia/Kolkata" with no zone of their own. This alias
// layer adds the missing high-search-volume city NAMES on top of the auto
// list (same live tz math, just an extra display entry) — still zero hand-typed
// offsets/abbreviations, just a name -> existing-zone pointer.
const ALIASES = [
  ["Mumbai", "Asia/Kolkata"], ["Bangalore", "Asia/Kolkata"], ["Chennai", "Asia/Kolkata"],
  ["Hyderabad", "Asia/Kolkata"], ["Pune", "Asia/Kolkata"], ["Delhi", "Asia/Kolkata"],
  ["Kolkata", "Asia/Kolkata"],
  ["San Francisco", "America/Los_Angeles"], ["Seattle", "America/Los_Angeles"],
  ["Las Vegas", "America/Los_Angeles"], ["San Diego", "America/Los_Angeles"],
  ["Boston", "America/New_York"], ["Washington DC", "America/New_York"],
  ["Miami", "America/New_York"], ["Atlanta", "America/New_York"],
  ["Houston", "America/Chicago"], ["Dallas", "America/Chicago"],
  ["Munich", "Europe/Berlin"], ["Frankfurt", "Europe/Berlin"],
  ["Milan", "Europe/Rome"], ["Manchester", "Europe/London"],
  ["Barcelona", "Europe/Madrid"], ["Osaka", "Asia/Tokyo"],
  ["Doha", "Asia/Qatar"], ["Tel Aviv", "Asia/Jerusalem"], ["Beijing", "Asia/Shanghai"],
];
for (const [city, tz] of ALIASES) {
  const slug = slugify(city);
  if (seenSlugs.has(slug)) continue;
  seenSlugs.add(slug);
  entries.push({ slug, city, region: tz.split("/")[0], tz });
}

// Hand-picked SLUGS ONLY (not data) for which pairs get static pSEO pages —
// generating all 418×417 pairs statically isn't practical. Everything in
// ALL_TIMEZONES (city names, tz names, regions) is still 100% auto-sourced above;
// this list just says "these are the high-traffic ones worth pre-building".
const FEATURED_SLUGS = [
  "utc", "new-york", "los-angeles", "chicago", "denver", "toronto", "vancouver",
  "mexico-city", "sao-paulo", "buenos-aires", "london", "paris", "berlin", "madrid",
  "rome", "amsterdam", "dublin", "lisbon", "zurich", "moscow", "istanbul", "athens",
  "dubai", "riyadh", "doha", "tel-aviv", "mumbai", "kolkata", "delhi", "karachi",
  "dhaka", "bangkok", "jakarta", "singapore", "kuala-lumpur", "manila", "hong-kong",
  "shanghai", "beijing", "seoul", "tokyo", "sydney", "melbourne", "auckland",
  "johannesburg", "cairo", "lagos", "nairobi", "san-francisco", "boston",
];

const banner = `// AUTO-GENERATED by scripts/generate-timezones.mjs — do not hand-edit.
// Source: Intl.supportedValuesOf("timeZone") — the live IANA/ICU database.
// Re-run the script to pick up new/renamed zones. Zero manual city entry.
`;

const out = `${banner}
export interface TZCity {
  slug: string;
  city: string;
  region: string; // IANA area, e.g. "America", "Asia", "Europe" — used for search grouping
  tz: string;      // canonical IANA timezone name
}

// Every IANA timezone Node/ICU knows about — ${entries.length} entries, auto-sourced.
export const ALL_TIMEZONES: TZCity[] = ${JSON.stringify(entries, null, 2)};

// Slugs pre-built as static pSEO pages (see [from]-to-[to].astro). Any OTHER
// city is still fully usable via the client-side Universal Converter search —
// nothing here limits what a visitor can actually convert.
export const FEATURED_SLUGS: string[] = ${JSON.stringify(FEATURED_SLUGS, null, 2)};

export const FEATURED_TIMEZONES: TZCity[] = ALL_TIMEZONES.filter((t) =>
  FEATURED_SLUGS.includes(t.slug)
);

export function findCity(slug: string): TZCity | undefined {
  return ALL_TIMEZONES.find((t) => t.slug === slug);
}
`;

writeFileSync(new URL("../src/data/timezones.ts", import.meta.url), out);
console.log(`Generated ${entries.length} timezones (${FEATURED_SLUGS.length} featured for static pages).`);
